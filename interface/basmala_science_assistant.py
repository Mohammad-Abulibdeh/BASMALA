def suggest_next_experiment(current_exp):
    """Suggest a related experiment based on similarity"""
    if not experiments_dict or current_exp not in experiments_dict:
        # Return a random experiment if current one is invalid
        available_exps = list(experiments_dict.keys())
        if available_exps:
            return np.random.choice(available_exps)
        return None
    
    current = experiments_dict[current_exp]
    
    # Simple keyword matching to find related experiments
    current_keywords = " ".join([
        current['name'],
        current.get('Principle', ''),
        current.get('Discovery', '')
    ]).lower()
    
    best_match = None
    best_score = 0
    
    for exp_no, exp_data in experiments_dict.items():
        if exp_no == current_exp or exp_no in state.experiments_discussed:
            continue
            
        exp_keywords = " ".join([
            exp_data['name'],
            exp_data.get('Principle', ''),
            exp_data.get('Discovery', '')
        ]).lower()
        
        # Simple similarity score based on word overlap
        words1 = set(re.findall(r'\w+', current_keywords))
        words2 = set(re.findall(r'\w+', exp_keywords))
        
        # Remove common words
        common_words = {'the', 'and', 'of', 'in', 'to', 'a', 'is', 'that', 'for'}
        words1 = words1 - common_words
        words2 = words2 - common_words
        
        if not words1 or not words2:
            continue
            
        intersection = words1.intersection(words2)
        score = len(intersection) / max(len(words1), len(words2))
        
        if score > best_score and score > 0.2:  # Minimum similarity threshold
            best_score = score
            best_match = exp_no
    
    # If no good match, return a random experiment
    if best_match is None:
        available_exps = list(set(experiments_dict.keys()) - state.experiments_discussed)
        if available_exps:
            best_match = np.random.choice(available_exps)
    
    return best_match

def handle_idle_time(idle_count):
    """Handle situations when the user is idle for some time"""
    if idle_count == 2:
        if state.selected_experiment_no:
            suggestion = suggest_next_experiment(state.selected_experiment_no)
            if suggestion:
                return f"Would you like to learn about experiment {suggestion} next? It's related to what we've been discussing."
        return "Do you have any other questions about the experiments? I'm here to help!"
    elif idle_count == 4:
        return "I noticed you haven't asked anything for a while. Would you like me to suggest an interesting experiment to explore?"
    elif idle_count >= 6:
        return "I'll be here when you're ready to continue. Just say hello to start again!"
    return None

def main():
    """Main function to run the Basmala assistant"""
    logger.info("Starting Basmala Science Assistant...")
    
    # Check if we have experiment data
    if not experiments_dict:
        error_msg = "No experiment data could be loaded. Please check the Excel file."
        logger.error(error_msg)
        print(error_msg)
        return
    
    # Introduction message
    welcome_message = "Hello! I'm Basmala, your science experiment assistant. I can help you explore our collection of experiments. Which experiment would you like to learn about?"
    speak(welcome_message)
    
    # Information about available experiments
    exp_count = len(experiments_dict)
    exp_range = f"1 to {max(experiments_dict.keys())}"
    speak(f"I have {exp_count} experiments available, numbered from {exp_range}. Just tell me which experiment number you'd like to explore.")
    
    idle_counter = 0
    last_activity_time = time.time()
    
    while True:
        # Check for idle time
        if time.time() - last_activity_time > 20:  # 20 seconds of inactivity
            idle_counter += 1
            idle_message = handle_idle_time(idle_counter)
            if idle_message:
                speak(idle_message)
            last_activity_time = time.time()
        
        # Get user input
        user_input = listen()
        
        # Reset idle counter if we got input
        if user_input:
            idle_counter = 0
            last_activity_time = time.time()
        else:
            continue
        
        # Check for text input fallback
        if user_input == "__text_input__":
            user_input = input("Your message: ")
            if not user_input:
                continue
        
        # Process user intent
        intent, info = get_enhanced_intent(user_input)
        logger.info(f"Detected intent: {intent}, info: {info}")
        
        # Handle different intents
        if intent == "farewell":
            speak("Thanks for exploring science with me today. Goodbye!")
            break
            
        elif intent == "greeting":
            if state.selected_experiment_no:
                speak(f"Hi there! We were discussing experiment {state.selected_experiment_no}. Would you like to continue or try a different experiment?")
            else:
                speak("Hello! I'd be happy to help you explore our science experiments. Which experiment number would you like to learn about?")
            
        elif intent == "experiment_number":
            try:
                no = int(info)
                if no in experiments_dict:
                    state.update_experiment(no)
                    response = summarize_experiment(no)
                    speak(f"{response} Which part would you like to know more about?")
                    
                    # List available sections
                    sections = [section for section in experiments_dict[no].keys() if section != 'name']
                    if sections:
                        speak(f"For this experiment, I have information about: {', '.join(sections)}.")
                else:
                    valid_range = f"1 to {max(experiments_dict.keys())}" if experiments_dict else "unknown"
                    speak(f"I don't have experiment {no} in my database. We have experiments from {valid_range}.")
            except ValueError:
                speak("I need a valid experiment number. Please try again.")
                
        elif intent == "experiment_section":
            if state.selected_experiment_no is None:
                speak("First, tell me which experiment number you're interested in.")
            else:
                section_info = get_section_info(state.selected_experiment_no, info)
                speak(section_info)
                
        elif intent == "question":
            response = get_contextual_response(user_input)
            speak(response)
            
        elif intent == "feedback":
            speak("Thank you for your feedback! Is there anything specific you'd like to know about the experiments?")
            
        else:
            # Default response for unclassified intents
            response = get_contextual_response(user_input)
            speak(response)
            
