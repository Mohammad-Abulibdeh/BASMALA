def speak_google_tts(text):
    """Enhanced TTS function with better error handling"""
    try:
        with tempfile.NamedTemporaryFile(delete=False, suffix='.mp3') as fp:
            temp_filename = fp.name
        
        # Break text into manageable chunks if too long
        if len(text) > 500:
            sentences = re.split(r'(?<=[.!?])\s+', text)
            chunks = []
            current_chunk = ""
            
            for sentence in sentences:
                if len(current_chunk) + len(sentence) < 500:
                    current_chunk += sentence + " "
                else:
                    chunks.append(current_chunk.strip())
                    current_chunk = sentence + " "
            
            if current_chunk:
                chunks.append(current_chunk.strip())
                
            for chunk in chunks:
                tts = gTTS(text=chunk, lang='en', slow=False)
                tts.save(temp_filename)
                
                pygame.mixer.init()
                pygame.mixer.music.load(temp_filename)
                pygame.mixer.music.play()
                while pygame.mixer.music.get_busy():
                    time.sleep(0.1)
        else:
            tts = gTTS(text=text, lang='en', slow=False)
            tts.save(temp_filename)
            
            pygame.mixer.init()
            pygame.mixer.music.load(temp_filename)
            pygame.mixer.music.play()
            while pygame.mixer.music.get_busy():
                time.sleep(0.1)
        
        os.unlink(temp_filename)
    except Exception as e:
        logger.error(f"Google TTS error: {e}")
        # Fallback to print only
        print(f"[SPEECH] {text}")

def speak(text):
    """Process and speak the given text"""
    # Keep original text for speaking
    speaking_text = text
    
    # Print to console
    logger.info(f"Basmala: {text}")
    
    # Add to conversation history
    conversation_history.append(f"Basmala: {text}")
    
    # Speak the text
    speak_google_tts(speaking_text)

def listen():
    """Enhanced speech recognition with noise reduction and better error handling"""
    recognizer = sr.Recognizer()
    
    try:
        with sr.Microphone() as source:
            print("Basmala: Listening...")
            
            # Dynamic noise adjustment
            recognizer.dynamic_energy_threshold = True
            recognizer.energy_threshold = 4000  # Higher threshold for noisy environments
            recognizer.dynamic_energy_adjustment_damping = 0.15
            recognizer.dynamic_energy_adjustment_ratio = 1.5
            
            # Adjust for ambient noise
            recognizer.adjust_for_ambient_noise(source, duration=0.5)
            
            try:
                # Capture audio with timeout
                audio = recognizer.listen(source, timeout=5, phrase_time_limit=10)
                
                # Try different speech recognition services for better results
                try:
                    print("Processing speech...")
                    text = recognizer.recognize_google(audio)
                    state.reset_listen_attempts()
                    print(f"You said: {text}")
                    conversation_history.append(f"User: {text}")
                    return text
                except sr.UnknownValueError:
                    attempts = state.increment_failed_listen()
                    if attempts <= 2:
                        speak("I didn't catch that. Could you please speak more clearly?")
                    else:
                        speak("I'm having trouble understanding. Try typing your question if speaking isn't working well.")
                    return ""
                except sr.RequestError:
                    # Try backup recognition service
                    try:
                        text = recognizer.recognize_sphinx(audio)
                        state.reset_listen_attempts()
                        print(f"You said (backup recognition): {text}")
                        conversation_history.append(f"User: {text}")
                        return text
                    except:
                        speak("Sorry, I'm having trouble with speech recognition right now.")
                        return ""
            except sr.WaitTimeoutError:
                speak("I didn't hear anything. Please try again.")
                return ""
            except Exception as e:
                logger.error(f"Error in speech recognition: {e}")
                speak("Something went wrong while listening.")
                return ""
    except Exception as e:
        logger.error(f"Error initializing microphone: {e}")
        # Fallback to text input
        speak("I'm having trouble with the microphone. Please type your input.")
        try:
            text = input("Your message: ")
            conversation_history.append(f"User: {text}")
            return text
        except:
            return ""

def extract_experiment_number(text):
    """Extract experiment numbers from text with improved pattern matching"""
    # Look for specific patterns like "experiment 12" or "number 7"
    patterns = [
        r'experiment\s+(\d+)',
        r'number\s+(\d+)',
        r'experiment\s*#\s*(\d+)',
        r'#\s*(\d+)',
        r'(\d+)'  # Fallback to any number
    ]
    
    for pattern in patterns:
        match = re.search(pattern, text, re.IGNORECASE)
        if match:
            try:
                return int(match.group(1))
            except ValueError:
                continue
    
    return None

def identify_section_name(text):
    """Improved section identification using fuzzy matching"""
    section_keywords = {
        "discovery": ["discovery", "find", "found", "discover"],
        "explanation": ["explanation", "explain", "why", "reason", "how it works"],
        "action": ["action", "do", "steps", "procedure", "how to", "instructions"],
        "principle": ["principle", "concept", "theory", "science behind", "law"],
        "expectation": ["expectation", "expect", "predict", "hypothesis", "should happen"],
        "observation": ["observation", "observe", "result", "outcome", "happen", "see"]
    }
    
    # Clean and lowercase the input text
    text_lower = text.lower()
    
    # Check each section's keywords
    section_scores = {}
    for section, keywords in section_keywords.items():
        score = 0
        for keyword in keywords:
            if keyword in text_lower:
                # Assign higher score for exact matches to primary keywords
                if keyword == section:
                    score += 3
                else:
                    score += 1
        section_scores[section] = score
    
    # Get the section with the highest score if any keyword was found
    if section_scores and max(section_scores.values()) > 0:
        return max(section_scores.items(), key=lambda x: x[1])[0]
    
    return None

def get_enhanced_intent(user_input):
    """Analyze user input to determine intent using context or Gemini"""
    try:
        # First try rule-based approach for efficiency
        user_input_lower = user_input.lower()
        
        # Basic intent recognition
        if any(greeting in user_input_lower for greeting in ["hi", "hello", "hey", "greetings"]):
            return "greeting", None
            
        if any(farewell in user_input_lower for farewell in ["bye", "goodbye", "exit", "quit", "see you"]):
            return "farewell", None
            
        # Check for experiment number requests
        exp_number = extract_experiment_number(user_input)
        if exp_number is not None:
            return "experiment_number", str(exp_number)
            
        # Check for section requests if we have a current experiment
        if state.selected_experiment_no is not None:
            section = identify_section_name(user_input)
            if section:
                return "experiment_section", section
        
        # If rule-based approach fails, use AI for more sophisticated analysis
        if model and state.chat_session:
            prompt = f"""
            Analyze this user input in the context of a science experiment assistant: '{user_input}'
            
            Current experiment: {state.selected_experiment_no if state.selected_experiment_no else 'None'}
            
            Classify the intent into ONE of these categories:
            1. greeting - General greeting or hello
            2. experiment_number - Request for information about a specific experiment number
            3. experiment_section - Request for a specific section of the current experiment
            4. question - General question about experiments or science
            5. feedback - User giving feedback or reaction
            6. farewell - User saying goodbye
            
            Return ONLY the category and any extracted info in this format:
            category|extracted_info
            
            For experiment_section, extracted_info should be one of: discovery, explanation, action, principle, expectation, observation
            """
            
            response = state.chat_session.send_message(prompt)
            result = response.text.strip().split("|")
            return result[0].strip().lower(), result[1].strip() if len(result) > 1 else None
        else:
            # Fallback without Gemini
            if "what" in user_input_lower or "how" in user_input_lower or "why" in user_input_lower:
                return "question", None
            return "question", None
        
    except Exception as e:
        logger.error(f"Error in intent recognition: {e}")
        # Fallback intent classification
        if "thank" in user_input_lower:
            return "feedback", None
        elif any(question_word in user_input_lower for question_word in ["what", "how", "why", "can", "could"]):
            return "question", None
        else:
            return "question", None

def get_section_info(experiment_no, section_name):
    """Get information about a specific section of an experiment"""
    # Standard section mapping
    section_map = {
        "discovery": "Discovery",
        "explanation": "Explanation",
        "action": "Action",
        "principle": "Principle",
        "expectation": "Expectation", 
        "observation": "Observation"
    }
    
    # Update last section in state
    state.last_section = section_name
    
    # Get experiment data
    experiment = experiments_dict.get(experiment_no, None)
    if not experiment:
        return f"Experiment {experiment_no} not found in our database."
    
    # Get section content
    section = section_map.get(section_name.lower(), None)
    if not section:
        # Try to find section with similar name
        for exp_section in experiment.keys():
            if section_name.lower() in exp_section.lower():
                section = exp_section
                break
    
    if not section or not section in experiment:
        return f"I don't have information about the {section_name} for experiment {experiment_no}."
    
    content = experiment[section]
    if not content or pd.isna(content):
        return f"The {section_name} for experiment {experiment_no} is not available."
    
    # Process content to make it more conversational
    if model and state.chat_session:
        prompt = f"""
        Rewrite this {section_name} information for experiment {experiment_no} in a conversational tone,
        keeping it under 3 sentences and sounding like an enthusiastic science assistant:
        
        {content}
        """
        
        try:
            response = state.chat_session.send_message(prompt)
            return response.text.strip()
        except Exception as e:
            logger.error(f"Error processing section content: {e}")
            return content
    else:
        # Simple formatting without Gemini
        if len(content) > 100:
            sentences = re.split(r'(?<=[.!?])\s+', content)
            if len(sentences) > 3:
                return " ".join(sentences[:3]) + "..."
        return content

