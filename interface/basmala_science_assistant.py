# Function to find and load Excel file with flexible column names
def load_experiments_data():
    # Look for Excel files in the current directory
    excel_files = glob.glob("*.xlsx")
    
    if not excel_files:
        logger.warning("No Excel files found in the current directory.")
        return DEFAULT_EXPERIMENTS
    
    # Try each Excel file
    for excel_path in excel_files:
        try:
            logger.info(f"Attempting to load experiment data from {excel_path}")
            df = pd.read_excel(excel_path)
            
            # Check for expected columns with flexible names
            name_column = None
            number_column = None
            
            # Try to identify column names
            for col in df.columns:
                col_lower = col.lower()
                if 'name' in col_lower or 'title' in col_lower or 'experiment' in col_lower:
                    name_column = col
                if 'no' in col_lower or 'num' in col_lower or 'id' in col_lower or '#' in col_lower:
                    number_column = col
            
            # If we couldn't find name column, try first string column
            if name_column is None:
                for col in df.columns:
                    if df[col].dtype == 'object':
                        name_column = col
                        break
            
            # If we couldn't find number column, use index + 1
            if number_column is None:
                df['ExperimentNo'] = df.index + 1
                number_column = 'ExperimentNo'
                
            logger.info(f"Using columns: {number_column} for experiment number, {name_column} for experiment name")
            
            # Build experiments dictionary
            experiments_dict = {}
            for _, row in df.iterrows():
                try:
                    exp_no = int(row[number_column]) if pd.notna(row[number_column]) else len(experiments_dict) + 1
                    exp_name = str(row[name_column]) if pd.notna(row[name_column]) else f"Experiment {exp_no}"
                    
                    # Create experiment entry
                    experiments_dict[exp_no] = {
                        'name': exp_name
                    }
                    
                    # Add all available columns as sections
                    for col in df.columns:
                        if col != number_column and col != name_column and pd.notna(row[col]):
                            # Map column names to standard section names if possible
                            section_name = col
                            for std_name in ['Discovery', 'Explanation', 'Action', 'Principle', 'Expectation', 'Observation']:
                                if std_name.lower() in col.lower():
                                    section_name = std_name
                                    break
                            
                            experiments_dict[exp_no][section_name] = str(row[col])
                            
                except (ValueError, TypeError) as e:
                    logger.warning(f"Skipping row due to error: {e}")
                    continue
            
            logger.info(f"Successfully loaded {len(experiments_dict)} experiments from {excel_path}")
            
            # If we have at least one experiment, return it
            if experiments_dict:
                return experiments_dict
                
        except Exception as e:
            logger.error(f"Error loading Excel file {excel_path}: {e}")
            
    # If we couldn't load any experiments, return default data
    logger.warning("Using default experiment data as fallback")
    return DEFAULT_EXPERIMENTS

