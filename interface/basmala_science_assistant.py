# Track the conversation state
class ConversationState:
    def __init__(self):
        self.selected_experiment_no = None
        self.last_section = None
        self.experiments_discussed = set()
        self.failed_listen_attempts = 0
        self.chat_session = model.start_chat(history=[]) if model else None
    
    def update_experiment(self, exp_no):
        if exp_no != self.selected_experiment_no:
            self.selected_experiment_no = exp_no
            self.last_section = None
            self.experiments_discussed.add(exp_no)
    
    def reset_listen_attempts(self):
        self.failed_listen_attempts = 0
    
    def increment_failed_listen(self):
        self.failed_listen_attempts += 1
        return self.failed_listen_attempts

